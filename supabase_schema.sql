create table if not exists public.student_registrations (
 id bigint generated by default as identity primary key,
 full_name text not null,
 phone text not null,
 email text,
 course text not null,
 message text,
 created_at timestamptz not null default now()
);

alter table public.student_registrations enable row level security;
grant insert on public.student_registrations to anon;
grant insert on public.student_registrations to authenticated;

drop policy if exists "Public can submit student registration" on public.student_registrations;
create policy "Public can submit student registration"
on public.student_registrations
for insert to anon, authenticated
with check (true);

